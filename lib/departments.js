/**
 * Detects whether a string looks like an internal identifier (UUID or obfuscated ID hash).
 */
export function isInternalIdentifier(str) {
  if (!str || typeof str !== "string") return false;
  const trimmed = str.trim();
  if (/^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i.test(trimmed)) {
    return true;
  }
  if (/[₹*^%$#@!~∂≤≈πΩ§∆Δøµ∑∫¥Ŧ]/.test(trimmed)) {
    return true;
  }
  const parts = trimmed.split("_");
  if (parts.length >= 2 && parts.some((p) => /[a-zA-Z]/.test(p) && /\d/.test(p))) {
    return true;
  }
  return false;
}

/**
 * Returns the human-readable display name for a given department name or ID.
 * Falls back safely to "Unknown Department" if it is an unmapped internal identifier,
 * or safely to the original value if it is already a human-readable name.
 */
export function getDepartmentDisplayName(nameOrId) {
  if (!nameOrId || typeof nameOrId !== "string") return nameOrId || "";
  const trimmed = nameOrId.trim();
  const entry = DEPARTMENT_PRESENTATION_MAP[trimmed];
  if (entry?.displayName) return entry.displayName;

  // Case-insensitive fallback match
  const lower = trimmed.toLowerCase();
  for (const [key, value] of Object.entries(DEPARTMENT_PRESENTATION_MAP)) {
    if (key.toLowerCase() === lower || value.displayName.toLowerCase() === lower) {
      return value.displayName;
    }
  }

  // Safe fallback for unmapped internal / obfuscated identifiers
  if (isInternalIdentifier(trimmed)) {
    return "Unknown Department";
  }

  return trimmed;
}

/**
 * Returns the human-readable description for a given department.
 * If the current description exists and is not obfuscated, returns it.
 * Otherwise returns the clean description from constants, or falls back safely.
 */
export function getDepartmentDescription(currentDesc, nameOrId) {
  const entry = nameOrId && typeof nameOrId === "string" ? DEPARTMENT_PRESENTATION_MAP[nameOrId.trim()] : null;
  if (entry?.description) {
    return entry.description;
  }
  return currentDesc || "";
}
